// No API key needed. Search public YouTube results only when the app reports a low pool.
// Candidates go into a review issue; videos are never added to the app without curation.
import fs from 'node:fs';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const context = vm.createContext({ window: {} });
vm.runInContext(fs.readFileSync(new URL('../videos.js', import.meta.url), 'utf8'), context);
const known = new Set(Object.values(context.window.VIDEOS).flat().map(v => v[0]));
async function get(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20000), headers: { 'User-Agent': 'Mozilla/5.0' } });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return response;
}
const needs = process.env.CONTENT_NEEDS_JSON ? JSON.parse(process.env.CONTENT_NEEDS_JSON)
  : await (await get('https://rad-mobility-sync-production.up.railway.app/content-needs')).json();
const queries = {
  morning: ['10 minute full body morning mobility follow along', '15 minute daily mobility routine no equipment', 'Tom Merrick 10 minute full body mobility follow along', 'Julia Reppel 10 minute morning mobility routine', 'EDR Fitness 15 minute full body mobility', '10 minute full body mobility daily beginner follow along'],
  evening: ['10 minute evening bedtime stretch wind down', '15 minute gentle evening mobility follow along', 'Yoga with Kassandra 10 minute bedtime stretch', 'Julia Reppel 10 minute evening mobility', 'Yoga with Bird 10 minute bedtime stretch', '10 minute evening full body stretch relaxation', 'SarahBethYoga 10 minute bedtime yoga', 'Yoga With Bird 10 minute evening full body stretch', 'Yoga with Uliana 10 minute bedtime yoga', 'Yoga with Kassandra 15 minute evening yoga unwind'],
};
const sections = [];
for (const mode of ['morning', 'evening']) {
  if (!needs[mode]) continue;
  const catalog = createHash('sha256').update(context.window.VIDEOS[mode].map(v => v[0]).sort().join(',')).digest('hex');
  if (needs[mode].catalog && needs[mode].catalog !== catalog) continue; // Superseded by a library update.
  const candidates = new Map(), failures = [];
  for (const query of queries[mode]) {
    const url = 'https://www.youtube.com/results?search_query=' + encodeURIComponent(query);
    try {
      const html = await (await get(url)).text();
      const raw = html.match(/(?:var\s+)?ytInitialData\s*=\s*(\{.*?\});<\/script>/s)?.[1];
      if (!raw) throw new Error('YouTube did not return readable search results');
      const walk = value => {
        if (!value || typeof value !== 'object') return;
        const v = value.videoRenderer;
        if (v?.videoId && !known.has(v.videoId)) {
          const length = v.lengthText?.simpleText;
          const seconds = length?.split(':').reduce((n, x) => n * 60 + Number(x), 0);
          if (seconds >= 5 * 60 && seconds <= 16 * 60 + 5) {
            const text = x => x?.simpleText || x?.runs?.map(r => r.text).join('') || '';
            candidates.set(v.videoId, { id: v.videoId, title: text(v.title), channel: text(v.ownerText), length });
          }
        }
        for (const child of Object.values(value)) if (typeof child === 'object') walk(child);
      };
      walk(JSON.parse(raw));
    } catch (error) { failures.push(`${query}: ${error.message}`); }
  }
  const safe = s => s.replace(/[\r\n]/g, ' ').replace(/[\[\]<>`*_]/g, '');
  sections.push(`## ${mode === 'morning' ? 'Regular mobility' : 'Wind-down'}\n\nA signed-in account has ${needs[mode].remaining} unseen routines remaining.\n\n` +
    [...candidates.values()].slice(0, 60).map(v => `- [ ] [${safe(v.title)}](https://www.youtube.com/watch?v=${encodeURIComponent(v.id)}) — ${safe(v.channel)}, ${v.length}`).join('\n') +
    (failures.length ? `\n\nSearch errors (retry or search manually):\n${failures.map(s => '- ' + safe(s)).join('\n')}` : '') +
    `\n\nSearch links: ${queries[mode].map(q => `[${q}](https://www.youtube.com/results?search_query=${encodeURIComponent(q)})`).join(' · ')}`);
}
if (!sections.length) { console.log('Both pools have enough unseen videos; no search needed.'); process.exit(0); }
const body = `The app has requested more videos before a pool runs out of unseen routines. Non-liked repeats need 60 other distinct completed routines in that pool first.\n\nReview these candidates for a full-body follow-along routine, no required equipment, appropriate regular/wind-down pacing, and working playback. Confirm the duration before adding to videos.js; bump the app version with the update.\n\n${sections.join('\n\n')}\n\nGenerated by the library refill workflow. Candidates are search results, not approved additions.`;
fs.writeFileSync('content-refill-report.md', body + '\n');
console.log(`Wrote content-refill-report.md (${sections.length} pools).`);
if (process.env.PUBLISH_ISSUE === '1') {
  const title = 'Refill the regular and wind-down video library';
  const issues = JSON.parse(execFileSync('gh', ['issue', 'list', '--repo', process.env.GITHUB_REPOSITORY, '--state', 'open', '--search', title + ' in:title', '--json', 'number,title'], { encoding: 'utf8' }));
  const issue = issues.find(x => x.title === title);
  execFileSync('gh', ['issue', issue ? 'edit' : 'create', ...(issue ? [String(issue.number)] : []), '--repo', process.env.GITHUB_REPOSITORY,
    '--title', title, '--body-file', 'content-refill-report.md'], { stdio: 'inherit' });
}
